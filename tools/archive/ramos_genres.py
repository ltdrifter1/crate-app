def _parse(b):
    out = set()
    for line in b.strip().splitlines():
        for n in line.split('|'):
            n = n.strip().lower()
            if n:
                out.add(n)
    return out


GENRE_SETS = [
    ('Metal',          _parse(METAL)),
    ('Hip-Hop',        _parse(HIPHOP)),
    ('R&B & Soul',     _parse(RNB_SOUL)),
    ('Jazz',           _parse(JAZZ)),
    ('Country & Folk', _parse(COUNTRY_FOLK)),
    ('Classical',      _parse(CLASSICAL)),
    ('Rock',           _parse(ROCK)),
]

RAMOS_GENRE = {}
for g, names in GENRE_SETS:
    for n in names:
        RAMOS_GENRE.setdefault(n, g)

DEFAULT = 'Electronic'
